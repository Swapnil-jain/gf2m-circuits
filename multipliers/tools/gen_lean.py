"""Emit a standalone Lean 4 file (core only, no Mathlib) proving by `decide +kernel` that a circuit computes
GF(2^m) multiplication mod P on EVERY input pair, plus refuted controls (a mutated circuit and a wrong P).

Pattern of ~/mobius-x1/lean/MobiusLean/Word.lean: values are `Nat` bitmasks, `gmul` is carry-less shift-and-add
with reduction, and every check is a `Bool` closed by `decide +kernel` (the kernel's GMP-accelerated Nat
land/xor/shift make this cheap). The pointwise statement is the theorem of record:

    allOk circ = true   where allOk := forall a < 2^m, forall b < 2^m, evalPt circ a b == gmul a b

Gates: (op, x, y) with op 1 = AND, 0 = XOR; signal s < 2m is an input (a_i = s, b_j = m + j), signal 2m + i is gate i.

    python3 gen_lean.py CIRCUIT --poly 0x11B --name Aes117 --out tools/lean/Aes117.lean
    python3 gen_lean.py --schoolbook 4 --poly 0x13 --name Gf16 --out tools/lean/Gf16.lean
Check (box):  nice -n 19 lean --threads=1 tools/lean/Aes117.lean
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from circuit import Circuit, load  # noqa: E402
import verify as V  # noqa: E402


def schoolbook_field(m, p):
    """Schoolbook product + reduction mod p: a small reference circuit (m^2 AND)."""
    n = 2 * m
    gates = []
    prod = [[] for _ in range(2 * m - 1)]
    for i in range(m):
        for j in range(m):
            gates.append(("AND", i, m + j))
            prod[i + j].append(n + len(gates) - 1)
    red = V.reduction_rows(m, p, 2 * m - 1)
    outs = []
    for t in range(m):
        terms = [s for k in range(2 * m - 1) if red[t] >> k & 1 for s in prod[k]]
        acc = terms[0]
        for s in terms[1:]:
            gates.append(("XOR", acc, s))
            acc = n + len(gates) - 1
        outs.append(acc)
    return Circuit(m, m, gates, outs)


def lean_list(c):
    return "[" + ", ".join(f"({1 if op == 'AND' else 0}, {x}, {y})" for op, x, y in c.gates) + "]"


def mutate(c):
    """First AND gate flipped to XOR (the must-fail control)."""
    d = c.copy()
    i = next(k for k, g in enumerate(d.gates) if g[0] == "AND")
    op, x, y = d.gates[i]
    d.gates[i] = ("XOR", x, y)
    return d, i


def chunk_text(m, A):
    """Pointwise check split by the value of a into chunks of A values (kernel memory stays small).
    allOkC conjoins every chunk explicitly, so it covers every a < 2^m and every b < 2^m."""
    k = (1 << m) // A
    lines = [f"def chunk (j : Nat) : Bool :=\n  (List.range {A}).all fun i => (List.range (2 ^ M)).all fun b =>\n"
             f"    evalPt gates outs ({A} * j + i) b == gmul P ({A} * j + i) b", ""]
    for j in range(k):
        lines.append(f"theorem chunk_{j} : chunk {j} = true := by decide +kernel")
    lines.append("")
    lines.append("/-- Every a in [0, 2^M) is " + str(A) + " * j + i with j < " + str(k) + ", i < " + str(A) + ". -/")
    lines.append("def allOkC : Bool := " + " && ".join(f"chunk {j}" for j in range(k)))
    lines.append("")
    lines.append("/-- The circuit equals GF(2^M) multiplication mod P on all 2^(2M) input pairs. -/")
    lines.append("theorem circuit_ok : allOkC = true := by\n  simp only [allOkC, " +
                 ", ".join(f"chunk_{j}" for j in range(k)) + ", Bool.and_self]")
    return "\n".join(lines)


def emit(c, p, name, A=None):
    m = c.na
    if A is None:
        A = max(1, (1 << m) // 64)
    assert c.nb == m and len(c.outputs) == m
    assert all(op in ("AND", "XOR") for op, _, _ in c.gates)
    wrong = V.other_irreducible(m, p)
    mut, mi = mutate(c)
    assert not V.exhaustive(mut, ("field", p)), "control mutant must fail in Python first"
    chunks = chunk_text(m, A)
    return f"""set_option autoImplicit false
set_option maxHeartbeats 0
set_option maxRecDepth 100000

/-!
# {name}: a {len(c.gates)}-gate circuit ({sum(g[0] == 'AND' for g in c.gates)} AND, {sum(g[0] == 'XOR' for g in c.gates)} XOR) computes multiplication in GF(2^{m}) = F_2[x]/({hex(p)})

Generated by tools/lean/gen_lean.py. Core Lean only, every proof `decide +kernel`.
Elements are `Nat` in [0, 2^{m}) with bit i the coefficient of x^i. `gmul` is shift-and-add with reduction.
Gates `(op, x, y)`: op 1 = AND, 0 = XOR; signals 0..{m - 1} are a_i, {m}..{2 * m - 1} are b_j, {2 * m} + i is gate i.
`evalPt` keeps every signal's bit in one `Nat` accumulator.
Controls: gate {mi} flipped from AND to XOR is refuted, and so is the circuit against the polynomial {hex(wrong)}.
-/

namespace {name}

def M : Nat := {m}

/-- Multiplication by x modulo `p` (degree M). -/
def xt (p a : Nat) : Nat := if (a <<< 1) &&& (1 <<< M) != 0 then (a <<< 1) ^^^ p else a <<< 1

/-- Carry-less product of a and b reduced mod p, by M shift-and-add rounds. -/
def gmulAux (p : Nat) : Nat → Nat → Nat → Nat → Nat
  | 0, _, _, r => r
  | k + 1, a, b, r => gmulAux p k (xt p a) (b >>> 1) (if b &&& 1 != 0 then r ^^^ a else r)

def gmul (p a b : Nat) : Nat := gmulAux p M a b 0

def run : List (Nat × Nat × Nat) → Nat → Nat → Nat
  | [], acc, _ => acc
  | (op, x, y) :: r, acc, idx =>
    let bx := (acc >>> x) &&& 1
    let bY := (acc >>> y) &&& 1
    let v := if op == 1 then bx &&& bY else bx ^^^ bY
    run r (acc ||| (v <<< idx)) (idx + 1)

def collect : List Nat → Nat → Nat → Nat
  | [], _, _ => 0
  | o :: r, acc, k => (((acc >>> o) &&& 1) <<< k) ||| collect r acc (k + 1)

def evalPt (gs : List (Nat × Nat × Nat)) (outs : List Nat) (a b : Nat) : Nat :=
  collect outs (run gs (a ||| (b <<< M)) (2 * M)) 0

def allOk (p : Nat) (gs : List (Nat × Nat × Nat)) (outs : List Nat) : Bool :=
  (List.range (2 ^ M)).all fun a => (List.range (2 ^ M)).all fun b => evalPt gs outs a b == gmul p a b

def P : Nat := {p}
def gates : List (Nat × Nat × Nat) := {lean_list(c)}
def outs : List Nat := {list(c.outputs)}
def gatesMut : List (Nat × Nat × Nat) := {lean_list(mut)}

/-- Sanity: `gmul` is the field multiplication: x * x^(M-1) reduces to the low part of P. -/
theorem gmul_sanity : gmul P 2 (1 <<< (M - 1)) = P ^^^ (1 <<< M) := by decide +kernel

{chunks}

/-- Control: the circuit with gate {mi} flipped AND -> XOR is wrong somewhere. -/
theorem control_mutant : allOk P gatesMut outs = false := by decide +kernel

/-- Control: the circuit is NOT multiplication modulo the other irreducible {hex(wrong)}. -/
theorem control_wrong_poly : allOk {wrong} gates outs = false := by decide +kernel

end {name}

#print axioms {name}.circuit_ok
#print axioms {name}.control_mutant
#print axioms {name}.control_wrong_poly
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("circuit", nargs="?")
    ap.add_argument("--schoolbook", type=int)
    ap.add_argument("--poly", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    p = int(a.poly, 0)
    c = schoolbook_field(a.schoolbook, p) if a.schoolbook else load(a.circuit)
    assert V.symbolic(c, ("field", p)) and V.exhaustive(c, ("field", p)), "circuit fails the Python verifier"
    with open(a.out, "w") as f:
        f.write(emit(c, p, a.name))
    print(a.out, len(c.gates), "gates")


if __name__ == "__main__":
    main()
