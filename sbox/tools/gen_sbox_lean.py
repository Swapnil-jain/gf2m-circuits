"""Emit Lean 4 (core only) proving a gate-list circuit equals the AES S-box TABLE on all 256 inputs.
Gates (op, x, y): signals 0-7 inputs, 8+i gate i; ops AND/XOR/XNOR. Bit convention is detected against the table.
    python3 gen_sbox_lean.py ../../results/commitment/sbox_110.json Sbox110 Sbox110.lean
"""
import json, os, sys

def sbox_table():
    def mul(a, b):
        r = 0
        while b:
            if b & 1: r ^= a
            a = (a << 1) ^ (0x11B if a & 0x80 else 0); b >>= 1
        return r & 0xFF
    t = []
    for x in range(256):
        inv = 0 if x == 0 else next(y for y in range(1, 256) if mul(x, y) == 1)
        s = 0
        for i in range(8):
            b = (inv >> i ^ inv >> ((i+4) % 8) ^ inv >> ((i+5) % 8) ^ inv >> ((i+6) % 8) ^ inv >> ((i+7) % 8) ^ 0x63 >> i) & 1
            s |= b << i
        t.append(s)
    assert t[0] == 0x63 and t[1] == 0x7C and t[0x53] == 0xED
    if os.environ.get('INV') == '1':          # AES INVERSE S-box table (INV=1)
        iv = [0] * 256
        for x in range(256): iv[t[x]] = x
        assert iv[0x63] == 0 and iv[0] == 0x52
        return iv
    return t

OPS = {"XOR": 0, "AND": 1, "XNOR": 2}

def ev(gates, outs, x, inrev, outrev):
    v = [(x >> (7 - i if inrev else i)) & 1 for i in range(8)]
    for op, a, b in gates:
        v.append({"XOR": v[a] ^ v[b], "AND": v[a] & v[b], "XNOR": 1 ^ v[a] ^ v[b]}[op])
    return sum(v[o] << (7 - k if outrev else k) for k, o in enumerate(outs))

def main():
    d = json.load(open(sys.argv[1])); name, out = sys.argv[2], sys.argv[3]
    g, outs, tab = d["gates"], d["outputs"], sbox_table()
    conv = [(ir, orv) for ir in (0, 1) for orv in (0, 1) if all(ev(g, outs, x, ir, orv) == tab[x] for x in range(256))]
    assert conv, "no bit convention matches the table"
    ir, orv = conv[0]
    # Lean reads input bit i of x as signal i (inrev: signal i = bit 7-i); outputs likewise.
    ib = "7 - i" if ir else "i"
    ob = "7 - k" if orv else "k"
    gl = "[" + ", ".join(f"({OPS[o]}, {a}, {b})" for o, a, b in g) + "]"
    mi = next(i for i, x in enumerate(g) if x[0] == "AND")
    gm = list(g); gm[mi] = ["XOR"] + gm[mi][1:]
    assert any(ev(gm, outs, x, ir, orv) != tab[x] for x in range(256))
    gml = "[" + ", ".join(f"({OPS[o]}, {a}, {b})" for o, a, b in gm) + "]"
    tw = list(tab); tw[0x53] ^= 1
    n = {"AND": 0, "XOR": 0, "XNOR": 0}
    for o, _, _ in g: n[o] += 1
    src = f"""set_option autoImplicit false
set_option maxHeartbeats 0
set_option maxRecDepth 100000

/-!
# {name}: a {len(g)}-gate circuit ({n['AND']} AND, {n['XOR']} XOR, {n['XNOR']} XNOR) equals the AES S-box on all 256 inputs

Generated by tools/lean/gen_sbox_lean.py from {sys.argv[1].split('/')[-1]}. Core Lean only, every proof `decide +kernel`.
`sbox` is the 256-entry FIPS-197 table (literal). Gates `(op, x, y)`: op 0 = XOR, 1 = AND, 2 = XNOR;
signals 0..7 are inputs, 8 + i is gate i. Input bit i of x is signal {'7 - i' if ir else 'i'}; output bit k is
signal outs[{'7 - k' if orv else 'k'}] (convention detected by exhaustive Python check against the table).
Controls: gate {mi} flipped AND -> XOR is refuted, and so is the table with entry 0x53 changed.
-/

namespace {name}

def sbox : List Nat := {tab}

def gates : List (Nat × Nat × Nat) := {gl}
def gatesMut : List (Nat × Nat × Nat) := {gml}
def outs : List Nat := {outs}
def sboxBad : List Nat := {tw}

def run : List (Nat × Nat × Nat) → Nat → Nat → Nat
  | [], acc, _ => acc
  | (op, x, y) :: r, acc, idx =>
    let bx := (acc >>> x) &&& 1
    let bY := (acc >>> y) &&& 1
    let v := if op == 1 then bx &&& bY else if op == 0 then bx ^^^ bY else 1 ^^^ bx ^^^ bY
    run r (acc ||| (v <<< idx)) (idx + 1)

/-- Input byte x placed so that signal s holds the bit the circuit expects. -/
def pack (x : Nat) : Nat := (List.range 8).foldl (fun acc i => acc ||| (((x >>> ({ib})) &&& 1) <<< i)) 0

def collect (acc : Nat) : List Nat → Nat → Nat
  | [], _ => 0
  | o :: r, k => (((acc >>> o) &&& 1) <<< ({ob})) ||| collect acc r (k + 1)

def evalPt (gs : List (Nat × Nat × Nat)) (x : Nat) : Nat := collect (run gs (pack x) 8) outs 0

def allOk (gs : List (Nat × Nat × Nat)) (t : List Nat) : Bool :=
  (List.range 256).all fun x => evalPt gs x == t.getD x 0

/-- The table has 256 entries. -/
theorem sbox_len : sbox.length = 256 := by decide +kernel

/-- For every 8-bit x, the circuit outputs equal sbox[x]. -/
theorem circuit_ok : allOk gates sbox = true := by decide +kernel

/-- Pointwise form of the statement. -/
theorem circuit_pointwise : ∀ x, x < 256 → evalPt gates x = sbox.getD x 0 := by
  intro x hx
  have h := circuit_ok
  simp only [allOk, List.all_eq_true, List.mem_range, beq_iff_eq] at h
  exact h x hx

/-- Control: one gate flipped is wrong somewhere. -/
theorem control_mutant : allOk gatesMut sbox = false := by decide +kernel

/-- Control: a wrong table entry is rejected. -/
theorem control_bad_table : allOk gates sboxBad = false := by decide +kernel

end {name}

#print axioms {name}.circuit_ok
#print axioms {name}.circuit_pointwise
#print axioms {name}.control_mutant
#print axioms {name}.control_bad_table
"""
    open(out, "w").write(src); print(out, conv)
main()
